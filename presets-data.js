window.matchTemaramPreset = function matchTemaramPreset(time, purpose) {
  let targetId = 'mystic-sanctum';
  if (purpose === 'focus') targetId = 'amber-study';
  else if (purpose === 'create') targetId = 'under-the-sea';
  else if (purpose === 'selfcare') targetId = 'midnight-retouch';
  else if (purpose === 'sleep') targetId = 'gentle-flow';
  else if (purpose === 'relax') {
    targetId = time === 'late-night' ? 'gentle-flow' : 'mystic-sanctum';
  }
  return (
    window.TLD_PRESETS.find((item) => item.id === targetId) ||
    window.TLD_PRESETS[1]
  );
};
